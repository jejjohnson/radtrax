"""v1's validation scene catalogue: the schema, the loader and the resolver (radtrax#122).

``tests/validation/scenes.toml`` lists the real scenes v1's gates run on
(#117 EMIT, #123 Sentinel-2, #124 Landsat 8/9). It is metadata, not imagery:
per scene, the sensor, the product identifier and its acquisition time, the
site, and the reference the gate compares against. The file is generated by
``scripts/build_scene_catalogue.py`` from public sources, and each entry names
its source and the record it was copied from; a source, in turn, carries its
citation, DOI or URL, and licence.

Two kinds of reference:

- ``metered_release``: a controlled release; the truth is the metered CH₄
  rate [kg/h] and its 1σ, averaged over the window that ends at
  ``window_end_utc`` (5 min in both sources). A zero rate is a control.
- ``coincident_emit``: the same plume seen by EMIT within ``max_dt_minutes``;
  the reference is that EMIT scene (its L2B CH₄ enhancement, and radtrax's own
  EMIT retrieval once #117 passes). The schema accepts it; the catalogue has
  no such entry yet.

A Sentinel-2 or Landsat release may name a ``clean_reference``: a catalogue
scene of the same orbit (relative orbit and tile, or WRS path and row) whose
metered rate is zero, the plume-free pass the multi-pass methods need.

The loader is a test helper, not radtrax API. It validates the whole file and
raises :class:`radtrax.ParameterError` naming the scene and the field. The
resolver needs ``radtrax[geo]`` (georeader) and the sensor's credentials, and
says which are missing.
"""

from __future__ import annotations

import datetime as dt
import os
import re
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from radtrax.exceptions import MissingExtraError, ParameterError


CATALOGUE = Path(__file__).parent / "validation" / "scenes.toml"
SCHEMA_VERSION = 1

#: The sensors v1 validates (radtrax#113), with the pattern of their product id.
PRODUCT_ID = {
    "EMIT": re.compile(r"^EMIT_L1B_RAD_001_(?P<date>\d{8})T\d{6}_\d{7}_\d{3}$"),
    "S2A": re.compile(
        r"^S2A_MSIL1C_(?P<date>\d{8})T\d{6}_N\d{4}_(?P<orbit>R\d{3})_(?P<tile>T\d{2}[A-Z]{3})_\d{8}T\d{6}$"
    ),
    "S2B": re.compile(
        r"^S2B_MSIL1C_(?P<date>\d{8})T\d{6}_N\d{4}_(?P<orbit>R\d{3})_(?P<tile>T\d{2}[A-Z]{3})_\d{8}T\d{6}$"
    ),
    "S2C": re.compile(
        r"^S2C_MSIL1C_(?P<date>\d{8})T\d{6}_N\d{4}_(?P<orbit>R\d{3})_(?P<tile>T\d{2}[A-Z]{3})_\d{8}T\d{6}$"
    ),
    "L8": re.compile(
        r"^LC08_L1(TP|GT)_(?P<path>\d{3})(?P<row>\d{3})_(?P<date>\d{8})_\d{8}_02_T[12]$"
    ),
    "L9": re.compile(
        r"^LC09_L1(TP|GT)_(?P<path>\d{3})(?P<row>\d{3})_(?P<date>\d{8})_\d{8}_02_T[12]$"
    ),
}
REFERENCE_KINDS = ("metered_release", "coincident_emit")

#: What each sensor's resolver needs, by environment variable or file.
CREDENTIALS = {
    "EMIT": "NASA Earthdata login: ~/.georeader/auth_emit.json (georeader.readers.emit.get_auth)",
    "S2": "Google Cloud access to gcp-public-data-sentinel-2: GOOGLE_APPLICATION_CREDENTIALS",
}


@dataclass(frozen=True)
class Source:
    """Where entries come from: a dataset, a paper or a product catalogue."""

    key: str
    citation: str
    url: str
    licence: str
    doi: str | None = None


@dataclass(frozen=True)
class Site:
    """A release site; ``lat``, ``lon`` in degrees (WGS84) of the release stack."""

    key: str
    name: str
    lat: float
    lon: float
    source: Source


@dataclass(frozen=True)
class Reference:
    """What a gate compares a scene with.

    ``metered_release``: ``rate_kg_h`` ± ``rate_sigma_kg_h`` (1σ) of CH₄ over the
    window ending at ``window_end_utc``. ``coincident_emit``: ``emit_scene``, an
    EMIT entry within ``max_dt_minutes``.
    """

    kind: str
    source: Source
    record: str
    rate_kg_h: float | None = None
    rate_sigma_kg_h: float | None = None
    window_end_utc: dt.datetime | None = None
    flow_stable: bool | None = None
    record_sha1: str | None = None
    wind_record: str | None = None
    emit_scene: str | None = None
    max_dt_minutes: float | None = None


@dataclass(frozen=True)
class Scene:
    """One catalogue entry."""

    id: str
    sensor: str
    product_id: str
    acquired_utc: dt.datetime
    product_source: Source
    site: Site
    reference: Reference
    cloud_cover_pct: float | None = None
    orbit: str | None = None
    l2b_ch4enh: str | None = None
    clean_reference: str | None = None

    @property
    def family(self) -> str:
        """``"EMIT"``, ``"S2"`` or ``"Landsat"``."""
        return {"E": "EMIT", "S": "S2", "L": "Landsat"}[self.sensor[0]]

    @property
    def licence(self) -> str:
        """The licence of the reference data (the product's is on ``product_source``)."""
        return self.reference.source.licence


def load_scene_catalogue(path: Path | str = CATALOGUE) -> tuple[Scene, ...]:
    """Read and validate the catalogue.

    Args:
        path: The TOML file; the committed catalogue by default.

    Returns:
        The scenes, in file order.

    Raises:
        ParameterError: The file breaks the schema; the message names the
            scene and the field.
    """
    return parse_scene_catalogue(tomllib.loads(Path(path).read_text(encoding="utf-8")))


def parse_scene_catalogue(data: dict[str, Any]) -> tuple[Scene, ...]:
    """Validate a parsed catalogue (see :func:`load_scene_catalogue`)."""
    if data.get("schema_version") != SCHEMA_VERSION:
        raise ParameterError(
            f"schema_version must be {SCHEMA_VERSION}, got {data.get('schema_version')!r}"
        )
    sources = {
        key: Source(
            key=key,
            **_fields(f"sources.{key}", raw, ("citation", "url", "licence"), ("doi",)),
        )
        for key, raw in data.get("sources", {}).items()
    }
    sites = {}
    for key, raw in data.get("sites", {}).items():
        fields = _fields(f"sites.{key}", raw, ("name", "lat", "lon", "source"), ())
        fields["source"] = _lookup(sources, fields["source"], f"sites.{key}.source")
        if not (-90.0 <= fields["lat"] <= 90.0 and -180.0 <= fields["lon"] <= 180.0):
            raise ParameterError(f"sites.{key}: lat/lon out of range")
        sites[key] = Site(key=key, **fields)
    scenes = [_scene(raw, sources, sites) for raw in data.get("scene", [])]
    if not scenes:
        raise ParameterError("the catalogue has no [[scene]] entries")
    by_id: dict[str, Scene] = {}
    for scene in scenes:
        if scene.id in by_id:
            raise ParameterError(f"scene id {scene.id!r} appears twice")
        by_id[scene.id] = scene
    for scene in scenes:
        _check_links(scene, by_id)
    return tuple(scenes)


def _scene(
    raw: dict[str, Any], sources: dict[str, Source], sites: dict[str, Site]
) -> Scene:
    where = f"scene {raw.get('id', '?')!r}"
    fields = _fields(
        where,
        raw,
        (
            "id",
            "sensor",
            "product_id",
            "acquired_utc",
            "product_source",
            "site",
            "reference",
        ),
        ("cloud_cover_pct", "orbit", "l2b_ch4enh", "clean_reference"),
    )
    sensor, product = fields["sensor"], fields["product_id"]
    if sensor not in PRODUCT_ID:
        raise ParameterError(f"{where}: sensor {sensor!r} not in {sorted(PRODUCT_ID)}")
    match = PRODUCT_ID[sensor].match(product)
    if match is None:
        raise ParameterError(
            f"{where}: product_id {product!r} is not a {sensor} product id"
        )
    acquired = _utc(fields["acquired_utc"], f"{where}.acquired_utc")
    if match["date"] != f"{acquired:%Y%m%d}":
        raise ParameterError(
            f"{where}: product_id date {match['date']} differs from acquired_utc {acquired:%Y-%m-%d}"
        )
    orbit = fields["orbit"]
    if sensor != "EMIT":
        expected = (
            f"{match['orbit']}_{match['tile']}"
            if sensor.startswith("S2")
            else f"P{match['path']}_R{match['row']}"
        )
        if orbit != expected:
            raise ParameterError(
                f"{where}: orbit {orbit!r} differs from the product id's {expected!r}"
            )
    l2b = fields["l2b_ch4enh"]
    if l2b is not None and (
        sensor != "EMIT"
        or re.fullmatch(r"EMIT_L2B_CH4ENH_\d{3}_" + product[17:], l2b) is None
    ):
        # product[17:] is the acquisition, "YYYYMMDDThhmmss_orbit_scene".
        raise ParameterError(
            f"{where}: l2b_ch4enh {l2b!r} is not the L2B CH4ENH of {product}"
        )
    cloud = fields["cloud_cover_pct"]
    if cloud is not None and not 0.0 <= cloud <= 100.0:
        raise ParameterError(f"{where}: cloud_cover_pct {cloud} not in [0, 100]")
    fields["acquired_utc"] = acquired
    fields["product_source"] = _lookup(
        sources, fields["product_source"], f"{where}.product_source"
    )
    fields["site"] = _lookup(sites, fields["site"], f"{where}.site")
    fields["reference"] = _reference(fields["reference"], sources, where)
    return Scene(**fields)


def _reference(
    raw: dict[str, Any], sources: dict[str, Source], where: str
) -> Reference:
    where = f"{where}.reference"
    kind = raw.get("kind")
    if kind not in REFERENCE_KINDS:
        raise ParameterError(f"{where}: kind {kind!r} not in {REFERENCE_KINDS}")
    if kind == "metered_release":
        required = (
            "kind",
            "source",
            "record",
            "rate_kg_h",
            "rate_sigma_kg_h",
            "window_end_utc",
        )
        optional = ("flow_stable", "record_sha1", "wind_record")
    else:
        required = ("kind", "source", "record", "emit_scene", "max_dt_minutes")
        optional = ()
    fields = _fields(where, raw, required, optional)
    fields["source"] = _lookup(sources, fields["source"], f"{where}.source")
    if kind == "metered_release":
        fields["window_end_utc"] = _utc(
            fields["window_end_utc"], f"{where}.window_end_utc"
        )
        if fields["rate_kg_h"] < 0.0 or fields["rate_sigma_kg_h"] < 0.0:
            raise ParameterError(
                f"{where}: a metered rate and its sigma are non-negative"
            )
    return Reference(**fields)


def _check_links(scene: Scene, by_id: dict[str, Scene]) -> None:
    where = f"scene {scene.id!r}"
    ref = scene.reference
    if ref.kind == "metered_release":
        assert ref.window_end_utc is not None
        if abs(scene.acquired_utc - ref.window_end_utc) > dt.timedelta(minutes=30):
            raise ParameterError(
                f"{where}: acquired_utc is more than 30 min from the release window"
            )
    else:
        emit = _lookup(by_id, ref.emit_scene, f"{where}.reference.emit_scene")
        assert ref.max_dt_minutes is not None
        if emit.sensor != "EMIT" or scene.family == "EMIT":
            raise ParameterError(
                f"{where}: a coincident reference pairs a Sentinel-2 or Landsat scene with an EMIT scene"
            )
        if abs(scene.acquired_utc - emit.acquired_utc) > dt.timedelta(
            minutes=ref.max_dt_minutes
        ):
            raise ParameterError(
                f"{where}: EMIT scene {emit.id!r} is more than {ref.max_dt_minutes} min away"
            )
    if scene.clean_reference is not None:
        clean = _lookup(by_id, scene.clean_reference, f"{where}.clean_reference")
        if clean.family != scene.family or clean.orbit != scene.orbit:
            raise ParameterError(
                f"{where}: clean_reference {clean.id!r} is not on the same orbit ({scene.orbit})"
            )
        if (
            clean.reference.kind != "metered_release"
            or clean.reference.rate_kg_h != 0.0
        ):
            raise ParameterError(
                f"{where}: clean_reference {clean.id!r} is not a metered zero release"
            )


def _fields(
    where: str, raw: Any, required: tuple[str, ...], optional: tuple[str, ...]
) -> dict[str, Any]:
    if not isinstance(raw, dict):
        raise ParameterError(f"{where}: expected a table")
    missing = [k for k in required if k not in raw]
    unknown = sorted(set(raw) - set(required) - set(optional))
    if missing or unknown:
        raise ParameterError(f"{where}: missing {missing}, unknown {unknown}")
    return {k: raw.get(k) for k in (*required, *optional)}


def _lookup(table: dict[str, Any], key: Any, where: str) -> Any:
    if key not in table:
        raise ParameterError(f"{where}: {key!r} is not defined")
    return table[key]


def _utc(value: Any, where: str) -> dt.datetime:
    if not isinstance(value, dt.datetime) or value.utcoffset() != dt.timedelta(0):
        raise ParameterError(
            f"{where}: expected a TOML datetime in UTC (…Z), got {value!r}"
        )
    return value


