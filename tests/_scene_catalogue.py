def missing_credentials(scene: Scene) -> list[str]:
    """What the resolver for ``scene`` lacks on this machine (empty when it can run)."""
    if scene.family == "EMIT":
        auth = Path.home() / ".georeader" / "auth_emit.json"
        ok = auth.is_file() and "SET-USER" not in auth.read_text(encoding="utf-8")
        return [] if ok else [CREDENTIALS["EMIT"]]
    if scene.family == "S2":
        return (
            []
            if os.environ.get("GOOGLE_APPLICATION_CREDENTIALS")
            else [CREDENTIALS["S2"]]
        )
    return ["a georeader Landsat Collection 2 L1 reader (spaceml-org/georeader#99)"]


def product_location(scene: Scene) -> str:
    """Where georeader reads the scene's product from.

    EMIT: the LP DAAC URL of the L1B radiance (``get_radiance_link``).
    Sentinel-2: the ``.SAFE`` folder in Google's public bucket, for
    ``S2ImageL1C`` (``s2_public_bucket_path``).

    Raises:
        MissingExtraError: georeader is not installed (``radtrax[geo]``), or,
            for EMIT, requests (georeader's EMIT reader imports it).
        ParameterError: no georeader reader for the sensor yet (Landsat,
            spaceml-org/georeader#99).
    """
    try:
        from georeader.readers import S2_SAFE_reader
    except ImportError as err:
        raise MissingExtraError(
            "resolving catalogue scenes needs the [geo] extra: pip install 'radtrax[geo]'"
        ) from err
    if scene.family == "EMIT":
        try:
            from georeader.readers import emit
        except (
            ImportError
        ) as err:  # georeader's EMIT reader imports requests, which [geo] lacks
            raise MissingExtraError(
                "resolving EMIT scenes needs the [geo] extra and requests: pip install 'radtrax[geo]' requests"
            ) from err
        return emit.get_radiance_link(scene.product_id)
    if scene.family == "S2":
        return S2_SAFE_reader.s2_public_bucket_path(
            scene.product_id + ".SAFE", check_exists=False
        )
    raise ParameterError(
        f"{scene.id}: georeader has no Landsat Collection 2 L1 reader yet (spaceml-org/georeader#99)"
    )
